def build_multiturn_session(turns: int) -> List[tuple]:
    """循环生成 turns 轮 (q, a) 会话，模拟长会话的历史膨胀。"""
    out = []
    for i in range(turns):
        q, a = _MULTITURN_PAIRS[i % len(_MULTITURN_PAIRS)]
        out.append((q, a))
    return out
